def test_duplicate_study_uid_rejected(migrated_db, account):
    from app.core.db import SessionLocal
    from app.modules.archive.models import Study
    from app.modules.patients.models import Patient
    uid = "1.2.826.0.1.3680043.8.498." + str(uuid.uuid4().int)[:20]
    with SessionLocal() as db:
        patient = Patient(name="Uji Coba")
        db.add(patient)
        db.flush()
        assert patient.mrn.startswith("MR")          # generated by PostgreSQL
        db.add(Study(study_instance_uid=uid, patient_id=patient.id))
        db.flush()
        db.add(Study(study_instance_uid=uid, patient_id=patient.id))
        with pytest.raises(IntegrityError):
            db.flush()
        db.rollback()


