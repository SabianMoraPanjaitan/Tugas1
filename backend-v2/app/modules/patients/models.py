"""Patient registry (master pasien)."""
from datetime import date, datetime

from sqlalchemy import CHAR, CheckConstraint, Date, DateTime, ForeignKey, Index, Text, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.core.db import Base


class Patient(Base):
    __tablename__ = "patients"
    __table_args__ = (
        CheckConstraint("sex IN ('M', 'F', 'O')", name="sex"),
        CheckConstraint("nik ~ '^[0-9]{16}$'", name="nik_digits"),
        CheckConstraint("satusehat_link IN ('found', 'created')", name="satusehat_link"),
        # fuzzy name search ("ahmad" finds "Ahmad Fauzi"); needs the pg_trgm extension
        Index("ix_patients_name_trgm", "name", postgresql_using="gin", postgresql_ops={"name": "gin_trgm_ops"}),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    # Hospital record number; also what we write into DICOM PatientID (0010,0020).
    # Generated by PostgreSQL: MR00000001, MR00000002, ...
    mrn: Mapped[str] = mapped_column(
        Text, unique=True, nullable=False,
        server_default=text("'MR' || lpad(nextval('patient_mrn_seq')::text, 8, '0')"))
    nik: Mapped[str | None] = mapped_column(CHAR(16), unique=True)          # national ID; optional
    ihs_number: Mapped[str | None] = mapped_column(Text, unique=True)        # SATUSEHAT Patient id
    satusehat_link: Mapped[str | None] = mapped_column(Text)                 # found | created
    name: Mapped[str] = mapped_column(Text, nullable=False)
    sex: Mapped[str | None] = mapped_column(Text)
    birth_date: Mapped[date | None] = mapped_column(Date)
    birth_place: Mapped[str | None] = mapped_column(Text)
    contact: Mapped[dict] = mapped_column(JSONB, nullable=False, server_default=text("'{}'::jsonb"))  # phone, address, city
    created_by: Mapped[int | None] = mapped_column(ForeignKey("users.id"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False,
                                                 server_default=func.now(), onupdate=func.now())
